/**************************** Strings ****************************/
// Strings are immutable . Strings can not be changed

let name = "Rohit";         // Strings can be created using Double Quotes
console.log(name);
console.log(name.length);


let name1 = 'Rishab';       // Strings can be created using Single Quotes
console.log(name1);
console.log(name1.length);


let name3 = "Amit";
console.log(`Boy name is ${name3}`);        // Literals Template

// Escape Sequence Characters
let name4 = `Subh\`am`;
console.log(name4);
console.log(name4.length);


let name5 = `Shr\navan`;
console.log(name5);
console.log(name5.length);


let name6 = `Man\rish`;
console.log(name6);
console.log(name6.length);


let name7 = `Riz\tvan`;
console.log(name7);
console.log(name7.length);
